// repoRoot is four levels up from this package (app/internal/pipeline/pr).
const repoRoot = "../../../.."

func staticTemplatePath(contentType string) string {
	return filepath.Join(repoRoot, ".github", "PULL_REQUEST_TEMPLATE", contentType+".md")
}

func metaTemplatePath(contentType string) string {
	return filepath.Join(repoRoot, "content", contentType, "meta.template.yaml")
}

// TestStaticTemplatesMatch keeps .github/PULL_REQUEST_TEMPLATE/<type>.md
// byte-identical to what RenderStaticTemplate produces. Run with
// CR_REGEN_TEMPLATES=1 to (re)generate the files after changing the template
// code; the normal run fails loudly on any drift.
func TestStaticTemplatesMatch(t *testing.T) {
	regen := os.Getenv("CR_REGEN_TEMPLATES") == "1"
	for _, ct := range KnownContentTypes {
		want := RenderStaticTemplate(ct)
		path := staticTemplatePath(ct)
		if regen {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatalf("mkdir: %v", err)
			}
			if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
				t.Fatalf("write %s: %v", path, err)
			}
			t.Logf("regenerated %s", path)
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read %s (run `CR_REGEN_TEMPLATES=1 go test ./internal/pipeline/pr/` to generate): %v", path, err)
		}
		if string(got) != want {
			t.Errorf("%s is out of sync with RenderStaticTemplate(%q).\nRegenerate with CR_REGEN_TEMPLATES=1.\n--- want ---\n%s\n--- got ---\n%s", path, ct, want, got)
		}
	}
}

// metaTemplateDoc is the slice of content/<type>/meta.template.yaml the PR
// template contract cares about.
type metaTemplateDoc struct {
	PRTemplate struct {
		Type   string   `yaml:"type"`
		Common []string `yaml:"common"`
		Fields []struct {
			Key string `yaml:"key"`
		} `yaml:"fields"`
	} `yaml:"pr_template"`
}

// TestTypeFieldsMatchMetaTemplate asserts the type-specific fields declared in
// template.go match the content type's meta.template.yaml pr_template.fields
// (plan §4: "driven by meta.template.yaml so template + validation contract
// stay in lock-step"). It also asserts the common-field set agrees.
func TestTypeFieldsMatchMetaTemplate(t *testing.T) {
	wantCommon := make([]string, len(commonFields))
	for i, f := range commonFields {
		wantCommon[i] = f.Key
	}

	for _, ct := range []string{ContentTypeBlog, ContentTypeSocial, ContentTypeNewsletter} {
		t.Run(ct, func(t *testing.T) {
			raw, err := os.ReadFile(metaTemplatePath(ct))
			if err != nil {
				t.Fatalf("read %s: %v", metaTemplatePath(ct), err)
			}
			var doc metaTemplateDoc
			if err := yaml.Unmarshal(raw, &doc); err != nil {
				t.Fatalf("parse %s: %v", metaTemplatePath(ct), err)
			}
			if doc.PRTemplate.Type != ct {
				t.Errorf("pr_template.type = %q, want %q", doc.PRTemplate.Type, ct)
			}

			gotKeys := make([]string, len(doc.PRTemplate.Fields))
			for i, f := range doc.PRTemplate.Fields {
				gotKeys[i] = f.Key
			}
			wantKeys := make([]string, len(typeFields[ct]))
			for i, f := range typeFields[ct] {
				wantKeys[i] = f.Key
			}
			if strings.Join(gotKeys, ",") != strings.Join(wantKeys, ",") {
				t.Errorf("%s pr_template.fields = %v, want %v (template.go typeFields)", ct, gotKeys, wantKeys)
			}
			if strings.Join(doc.PRTemplate.Common, ",") != strings.Join(wantCommon, ",") {
				t.Errorf("%s pr_template.common = %v, want %v", ct, doc.PRTemplate.Common, wantCommon)
			}
		})
	}
}

func TestContentTypeMapping(t *testing.T) {
	cases := map[string]string{
		"blog":         ContentTypeBlog,
		"BLOG":         ContentTypeBlog,
		" social ":     ContentTypeSocial,
		"newsletter":   ContentTypeNewsletter,
		"short":        DefaultContentType,
		"tutorial":     DefaultContentType,
		"teleprompter": DefaultContentType,
		"":             DefaultContentType,
	}
	for in, want := range cases {
		if got := ContentType(in); got != want {
			t.Errorf("ContentType(%q) = %q, want %q", in, got, want)
		}
	}
	if got := TemplateQueryParam("blog"); got != "blog.md" {
		t.Errorf("TemplateQueryParam(blog) = %q", got)
	}
}

// TestPRBodyUsesTypeTemplateAndPrefills checks PRBody renders the blog template
// for a blog run, pre-fills the common fields it knows, surfaces the
// blog-specific checklist, and still carries the real clearance block + Closes.
func TestPRBodyUsesTypeTemplateAndPrefills(t *testing.T) {
	rc, s, m := runContext(), teleprompterSample(), cleanMix()
	body := PRBody(rc, s, m)

	for _, want := range []string{
		"content PR template: blog",
		"## 🎛️ Recycled blog — generated by ContentRemixer",
		"Closes #42",
		"- **Content type:** blog",
		"- **Source URL / original asset:** content/videos/2026/demo-video",
		"- **Target format:** blog",
		"- **Slug:** 42-blog-demo-video",
		"### Blog fields",
		"- [ ] **Primary keyword:**",
		"- [ ] **Meta description:** (140–160 characters)",
		"- [ ] **Sources section present:**",
		"## Sample clearance",
		"- **Source commit:** " + testCommit,
		"- **Model:** anthropic/claude-opus-4",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("PR body missing %q; got:\n%s", want, body)
		}
	}
	// Summary pre-filled from the first body paragraph.
	if !strings.Contains(body, "- **Summary:** You committed a token. It happens.") {
		t.Errorf("PR body summary not pre-filled; got:\n%s", body)
	}
	// Placeholder must not leak for fields we pre-filled.
	if strings.Contains(body, "- **Source URL / original asset:** "+fillIn) {
		t.Errorf("source field left as placeholder; got:\n%s", body)
	}
}

// TestPRBodyUnknownFormatFallsBackToDefault ensures assembly never fails for an
// output format without a dedicated template.
func TestPRBodyUnknownFormatFallsBackToDefault(t *testing.T) {
	rc, s, m := runContext(), teleprompterSample(), cleanMix()
	rc.OutputFormat = "teleprompter"
	m.OutputFormat = "teleprompter"
	body := PRBody(rc, s, m)
	for _, want := range []string{
		"content PR template: default",
		"## 🎛️ Recycled content — generated by ContentRemixer",
		"### Type-specific fields",
		"## Sample clearance",
		"Closes #42",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("default PR body missing %q; got:\n%s", want, body)
		}
	}
}

