#!/usr/bin/env python3
"""Emit the web design-system token layer from the single source of truth.

Sibling to build_kit.py: both read branding/kit/tokens.json. Where build_kit.py
bakes the brand into SVG/PNG, this emits the *web* token layer the Vite/React SPA
(booth/web) consumes:

  * tokens.css  — :root primitives (--cr-violet …) + a semantic layer mapped for
                  light (:root) and dark ([data-theme="dark"]) themes, driving the
                  validated A2 light/dark toggle.
  * tokens.ts   — the same tokens as a typed module for component props & charts.

The primitives come verbatim from tokens.json (palette + gradients), so no hex is
hand-copied. The semantic layer (surface/text/border/… per theme) is a curated
design mapping expressed here against those primitives; it regenerates
deterministically, so CI can diff the committed output against a fresh run
(lockstep: tokens.json must not drift from tokens.css/tokens.ts).

Usage:  python3 branding/kit/build/build_css.py            # write files
        python3 branding/kit/build/build_css.py --check     # exit 1 if drifted
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HERE)
TOKENS_JSON = os.path.join(KIT, "tokens.json")
OUT_DIR = os.path.normpath(os.path.join(KIT, "..", "..", "booth", "web", "src", "styles"))
CSS_OUT = os.path.join(OUT_DIR, "tokens.css")
TS_OUT = os.path.join(OUT_DIR, "tokens.ts")

HEADER = (
    "/* GENERATED by branding/kit/build/build_css.py from branding/kit/tokens.json.\n"
    " * Do not edit by hand — change tokens.json and re-run the build. CI enforces\n"
    " * that this file matches a fresh generation (tokens lockstep). */\n"
)


def slug(name: str) -> str:
    """palette key -> css-var suffix (already kebab in tokens.json)."""
    return name.strip().lower().replace(" ", "-")


def camel(name: str) -> str:
    parts = slug(name).split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def load_tokens() -> dict:
    with open(TOKENS_JSON, encoding="utf-8") as f:
        return json.load(f)


# --- Semantic layer ------------------------------------------------------------
# Curated mapping from brand primitives to UI roles, per theme. Values are
# css-var references to the primitives emitted above (var(--cr-...)) or literals
# derived from them. Kept here (not in tokens.json) because the light/dark UI
# mapping is a design decision layered on top of the brand primitives.
SEMANTIC = {
    # role:            (light value,                     dark value)
    "bg":              ("#F5F3FF",                        "var(--cr-bg-2)"),
    "surface":         ("#FFFFFF",                        "var(--cr-bg-1)"),
    "surface-2":       ("#F0EDFB",                        "#221A42"),
    "surface-raised":  ("#FFFFFF",                        "#271E4C"),
    "border":          ("#E4DEF7",                        "#312E5A"),
    "border-strong":   ("#CFC6EE",                        "#413B6E"),
    "text":            ("var(--cr-bg-1)",                 "var(--cr-white)"),
    "text-muted":      ("#6B6490",                        "#A79FC9"),
    "text-inverted":   ("var(--cr-white)",                "var(--cr-bg-1)"),
    "primary":         ("var(--cr-violet)",               "var(--cr-glyph-lavender)"),
    "primary-contrast":("var(--cr-white)",                "var(--cr-bg-2)"),
    "accent":          ("var(--cr-magenta)",              "var(--cr-magenta)"),
    "warn":            ("var(--cr-orange)",               "var(--cr-glyph-orange)"),
    "sidebar-bg":      ("#FFFFFF",                        "var(--cr-bg-1)"),
    "topbar-bg":       ("#FFFFFFCC",                      "#1A1235CC"),
    "focus-ring":      ("var(--cr-violet)",               "var(--cr-glyph-lavender)"),
}

SCALARS = {
    # non-color design scalars, theme-invariant
    "radius-sm": "6px",
    "radius-md": "10px",
    "radius-lg": "16px",
    "radius-pill": "999px",
    "font-sans": "'Poppins', ui-sans-serif, system-ui, -apple-system, 'Segoe UI', sans-serif",
    "shadow-card": "0 1px 2px rgba(26,18,53,0.06), 0 4px 16px rgba(26,18,53,0.08)",
    "glow": "0 0 24px rgba(124,58,237,0.35)",
}


def build_css(tok: dict) -> str:
    palette = tok["palette"]
    gradients = tok["gradients"]

    prim_lines = []
    for key, meta in palette.items():
        prim_lines.append(f"  --cr-{slug(key)}: {meta['hex']};")
    # gradients
    for gname, g in gradients.items():
        stops = ", ".join(g["stops"])
        horizontal = "to right" if "horizontal" in g["angle"] else "135deg"
        prim_lines.append(f"  --cr-gradient-{slug(gname)}: linear-gradient({horizontal}, {stops});")
    # scalars
    for k, v in SCALARS.items():
        prim_lines.append(f"  --cr-{k}: {v};")

    light_lines = [f"  --cr-{role}: {light};" for role, (light, _dark) in SEMANTIC.items()]
    dark_lines = [f"  --cr-{role}: {dark};" for role, (_light, dark) in SEMANTIC.items()]

    nl = "\n"
    return (
        HEADER
        + "\n:root {\n"
        + "  /* --- brand primitives (verbatim from tokens.json) --- */\n"
        + nl.join(prim_lines)
        + "\n\n  /* --- semantic layer: light (default) --- */\n"
        + nl.join(light_lines)
        + "\n}\n\n"
        + '[data-theme="dark"] {\n'
        + "  /* --- semantic layer: dark overrides --- */\n"
        + nl.join(dark_lines)
        + "\n}\n"
    )


def build_ts(tok: dict) -> str:
    palette = tok["palette"]
    gradients = tok["gradients"]

    prim = {f"cr-{slug(k)}": v["hex"] for k, v in palette.items()}
    grad = {}
    for gname, g in gradients.items():
        horizontal = "to right" if "horizontal" in g["angle"] else "135deg"
        grad[slug(gname)] = f"linear-gradient({horizontal}, {', '.join(g['stops'])})"

    def obj(d: dict, indent: str = "  ") -> str:
        return "\n".join(f'{indent}"{k}": "{v}",' for k, v in d.items())

    semantic_vars = {role: f"var(--cr-{role})" for role in SEMANTIC}
    scalar_vars = {k: f"var(--cr-{k})" for k in SCALARS}

    return (
        HEADER
        + "\n// Typed token module — mirrors tokens.css. Primitives are literal hex\n"
        + "// (safe for canvas/chart contexts); semantic + scalar tokens are css-var\n"
        + "// references so they follow the active [data-theme].\n\n"
        + "export const primitives = {\n"
        + obj(prim)
        + "\n} as const;\n\n"
        + "export const gradients = {\n"
        + obj(grad)
        + "\n} as const;\n\n"
        + "export const semantic = {\n"
        + obj(semantic_vars)
        + "\n} as const;\n\n"
        + "export const scalars = {\n"
        + obj(scalar_vars)
        + "\n} as const;\n\n"
        + "export type PrimitiveToken = keyof typeof primitives;\n"
        + "export type SemanticToken = keyof typeof semantic;\n"
        + "export const tokens = { primitives, gradients, semantic, scalars } as const;\n"
        + "export default tokens;\n"
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    tok = load_tokens()
    css = build_css(tok)
    ts = build_ts(tok)

    if check:
        drift = []
        for path, content in ((CSS_OUT, css), (TS_OUT, ts)):
            existing = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8") as f:
                    existing = f.read()
            if existing != content:
                drift.append(path)
        if drift:
            sys.stderr.write(
                "tokens drift: the following are out of sync with tokens.json; "
                "re-run build_css.py and commit:\n  - "
                + "\n  - ".join(drift)
                + "\n"
            )
            return 1
        print("tokens in lockstep with tokens.json")
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(CSS_OUT, "w", encoding="utf-8") as f:
        f.write(css)
    with open(TS_OUT, "w", encoding="utf-8") as f:
        f.write(ts)
    print(f"wrote {os.path.relpath(CSS_OUT)}")
    print(f"wrote {os.path.relpath(TS_OUT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
